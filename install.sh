#!/bin/sh
# =============================================================================
#  BariStore Installer — One-line installer & updater for a-Shell (MIT)
#
#  In a-Shell, run from anywhere:
#      curl -fsSL https://raw.githubusercontent.com/barismd/BariStore/main/install.sh | sh
#
#  What it creates in ~/Documents:
#      baristore          the launcher: run `baristore` from ~/Documents
#      baristore_files/   program package, certificates, sources.json, state/
# =============================================================================

set -u

case "$0" in
*/baristore_files/install.sh|install.sh)
    _self=".install.sh.run-$$"
    cp -f "$0" "$_self" || exit 1
    exec sh "$_self" "$@"
    ;;
esac
for _old in .install.sh.run-*; do
    case "$_old" in
        *"$$") ;;
        *) rm -f "$_old" ;;
    esac
done

DOCS="$HOME/Documents"
PROG="${BARISTORE_DIR:-$DOCS/baristore_files}"

mkdir -p "$PROG/baristore" "$PROG/third_party/apple-roots" "$PROG/third_party/ca-bundle" || {
    printf '  ! cannot create %s (a-Shell only writes inside ~/Documents)\n' "$PROG"
    exit 1
}
cd "$PROG" || exit 1

REPO="barismd/BariStore"
SHA=$(curl -sSL --max-time 20 "https://github.com/$REPO/commits/main.atom" 2>/dev/null | python3 -c "
import re, sys
found = re.search(r'commit/([0-9a-f]{40})', sys.stdin.read())
print(found.group(1) if found else '')
" 2>/dev/null)

if [ -n "${SHA:-}" ]; then
    RAW="https://raw.githubusercontent.com/$REPO/$SHA"
else
    RAW="https://raw.githubusercontent.com/$REPO/main"
fi

VER=$(curl -fsSL --connect-timeout 15 --max-time 45 -H 'Cache-Control: no-cache' \
    "$RAW/baristore/__init__.py" 2>/dev/null | python3 -c "
import re, sys
m = re.search(r'VERSION *= *[\"\x27]([^\"\x27]+)[\"\x27]', sys.stdin.read())
print(m.group(1) if m else '')
" 2>/dev/null)
: "${VER:=}"

FILES="baristore/__init__.py baristore/cli.py baristore/storage.py baristore/tls_psk.py \
       baristore/tcp6.py baristore/remote_xpc.py baristore/pairing.py baristore/mdns.py \
       baristore/tunnel.py baristore/device.py baristore/apple.py baristore/signer.py \
       baristore/sources.py baristore/webui.py baristore/ui_page.py \
       third_party/apple-roots/apple-roots.pem third_party/ca-bundle/cacert.pem \
       sources.json baristore.svg install.sh"

fetch() {
    if curl -fsSL --connect-timeout 15 --max-time 90 -H 'Cache-Control: no-cache' \
            "$RAW/$1" -o "$2" 2>/dev/null && [ -s "$2" ]; then
        return 0
    fi
    if curl -fsSL --connect-timeout 15 --max-time 90 -H 'Cache-Control: no-cache' \
            "https://raw.githubusercontent.com/$REPO/main/$1" -o "$2" 2>/dev/null && [ -s "$2" ]; then
        return 0
    fi
    FAILED="${FAILED:-} $1"
    return 1
}

download_all() {
    fail=0
    _n=0
    _updated=0
    _current=0
    for _file in $FILES; do
        if fetch "$_file" "$_file.part"; then
            _n=$((_n + 1))
            if [ -f "$_file" ] && python3 -c "import sys,hashlib
a = hashlib.sha256(open(sys.argv[1],'rb').read()).digest()
b = hashlib.sha256(open(sys.argv[2],'rb').read()).digest()
sys.exit(0 if a == b else 1)" "$_file" "$_file.part" 2>/dev/null; then
                _current=$((_current + 1))
                rm -f "$_file.part"
            else
                _updated=$((_updated + 1))
                mv -f "$_file.part" "$_file"
            fi
        else
            _n=$((_n + 1))
            fail=1
            rm -f "$_file.part"
        fi
        printf '\r\033[2K  downloading files (%d)...' "$_n"
    done

    # The launcher is generated by Python with the absolute program path baked
    # in: no `cd`, no `dirname "$0"`, no nested quoting (a-Shell's sh choked on
    # that), and it never moves the user's shell.
    python3 - "$DOCS/baristore" "$PROG" <<'PYLAUNCH' || return 1
import os, sys

path, prog = sys.argv[1], sys.argv[2]
lines = [
    "#!/bin/sh",
    "# BariStore launcher - works from any directory.",
    'PYTHONPATH="%s"' % prog,
    "export PYTHONPATH",
    'python3 -u -m baristore.cli "$@"',
    "status=$?",
    'if [ "$status" -ne 0 ]; then',
    "  printf 'BariStore failed (status %s); log: " + prog + "/state/launch.log\\n' \"$status\"",
    "fi",
    "exit $status",
    "",
]
tmp = path + ".tmp"
with open(tmp, "w") as handle:
    handle.write("\n".join(lines))
os.chmod(tmp, 0o755)
os.replace(tmp, path)
PYLAUNCH
    chmod +x "$DOCS/baristore" 2>/dev/null
    return $fail
}

works() {
    PYTHONPATH="$PROG" python3 -m baristore.cli --check >/dev/null 2>&1 \
        && sh -n "$DOCS/baristore" \
        && sh "$DOCS/baristore" --version >/dev/null 2>&1
}

printf 'Installing BariStore%s...\n' "${VER:+" $VER"}"
FAILED=""
download_all
printf '\n'

if [ "$fail" -ne 0 ] || ! works; then
    printf '  ! install failed.\n'
    if [ -n "${FAILED:-}" ]; then
        printf '  ! could not fetch:%s\n' "$FAILED"
    fi
    exit 1
fi

printf 'BariStore %s installed!\n\n' "${VER:-}"
printf '  Run in a-Shell (from any folder):\n'
printf '    baristore\n'
printf '  If the launcher ever fails, this always works:\n'
printf '    python3 -m baristore.cli\n'
